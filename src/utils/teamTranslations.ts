/**
 * Normalizes an English string by stripping diacritics, punctuation, extra spaces, and common club acronyms
 * (Preserves key identifying words like United, City, Madrid, Milan, Betis, Sociedad, etc.)
 */
function normalizeName(str: string): string {
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // remove diacritics (é -> e, á -> a, etc.)
    .toLowerCase()
    .replace(/\b(fc|cf|ssc|rcd|ud|cd|sd|ca|us|ac|as|bvb|afc|ogc|sc|sk|bsc|hsc|1\.|04|05|09|1899|1909|1910|1913|1848|1846|1901|1919|1989|29|63|1907|1913)\b/gi, ' ')
    .replace(/[^a-z0-9]/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// Precomputed case-insensitive dictionary
const LOWER_LOOKUP: Record<string, string> = {};
// Precomputed normalized dictionary for O(1) matching
const NORMALIZED_LOOKUP: Record<string, string> = {};

for (const [key, value] of Object.entries(TEAM_AR_NAMES)) {
  LOWER_LOOKUP[key.toLowerCase().trim()] = value;
  const norm = normalizeName(key);
  if (norm && !NORMALIZED_LOOKUP[norm]) {
    NORMALIZED_LOOKUP[norm] = value;
  }
}

/**
 * Translates any English team name into its official Arabic name safely without cross-matching.
 */
export function getArabicTeamName(rawName?: string | null): string {
  if (!rawName) return 'فريق';
  const name = String(rawName).trim();
  if (!name) return 'فريق';

  // 1. Direct match in dictionary
  if (TEAM_AR_NAMES[name]) {
    return TEAM_AR_NAMES[name];
  }

  // 2. Fast case-insensitive match
  const lower = name.toLowerCase();
  if (LOWER_LOOKUP[lower]) {
    return LOWER_LOOKUP[lower];
  }

  // 3. Fast normalized match (strips diacritics & standard club prefixes like FC, CF, etc.)
  const norm = normalizeName(name);
  if (norm && NORMALIZED_LOOKUP[norm]) {
    return NORMALIZED_LOOKUP[norm];
  }

  // 4. Exact word boundary match for longer names
  for (const [k, v] of Object.entries(TEAM_AR_NAMES)) {
    const kNorm = normalizeName(k);
    if (kNorm.length >= 5 && norm === kNorm) {
      return v;
    }
  }

  // 5. If already contains Arabic characters, return as is
  if (/[\u0600-\u06FF]/.test(name)) {
    return name;
  }

  // 6. Clean fallback: remove common English club acronyms and return clean title
  return name
    .replace(/\b(FC|CF|SSC|RCD|UD|CD|SD|CA|US|AC|AS|AFC|OGC|BSC|HSC)\b/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

